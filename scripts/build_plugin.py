"""Render the marketplace activity component from the tested legacy template.

Keep the template and legacy generated installations byte-compatible; the new
component differs only in command/threshold properties. Commit the result so
Omarchy can load the repository directly, without a build hook.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def activity_source():
    source = (ROOT / "diurna/shell_plugin/Service.qml").read_text(encoding="utf-8")
    source = source.replace("    property var queue: []", """    property var command: ["diurna"]
    property int idleSeconds: 150
    property int handsOnSeconds: 60
    property var queue: []""")
    source = source.replace('[@PROGRAM@, "signal"].concat(queue[0])',
                            'root.command.concat(["signal"], queue[0])')
    source = source.replace("@TIMEOUT@", "root.idleSeconds")
    source = source.replace("@HANDS_ON@", "root.handsOnSeconds")
    return "// Generated by scripts/build_plugin.py; edit the legacy template instead.\n" + source


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "plugin/Activity.qml"
    source = activity_source()
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != source:
            raise SystemExit("plugin/Activity.qml is stale; run python3 scripts/build_plugin.py")
    else:
        target.parent.mkdir(exist_ok=True)
        target.write_text(source, encoding="utf-8")
